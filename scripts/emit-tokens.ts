/**
 * Emits the five token levels as SCSS from the TypeScript sources.
 *
 *   src/tokens/primitives.ts           → src/styles/tokens/_l1-primitives.scss
 *   src/tokens/semantic.ts             → src/styles/tokens/_l2-semantic.scss
 *   component meta (+ tokens.ts)       → _l3-component.scss, _l4-role.scss, _l5-state.scss
 *
 * Component specs come from `src/components/<Name>/schema.ts` (its `meta`
 * export) with optional overrides in `src/components/<Name>/tokens.ts`, and
 * from `src/tokens/specs/<name>.ts` for styled things that are not components
 * (page elements, layout primitives). Run `bun scripts/emit-tokens.ts --show`
 * to print the hierarchy and CSS variable names without writing files.
 */
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { primitives, palettes } from "../src/tokens/primitives";
import { semantic, light, palette } from "../src/tokens/semantic";
import
  { generateComponent, generateTokenHierarchy, toCSSVariables, validateFoundations
  , type Spec, type ComponentTokens, type Token
  } from "../src/tokens/generate";

const root = join(fileURLToPath(import.meta.url), "../..");
const COMPONENTS = join(root, "src/components");
const SPECS = join(root, "src/tokens/specs");
const OUT = join(root, "src/styles/tokens");

const loadSpecs = async (): Promise<Spec[]> => {
  const specs: Spec[] = [];
  for (const entry of readdirSync(COMPONENTS, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const schema = join(COMPONENTS, entry.name, "schema.ts");
    if (!existsSync(schema)) continue;
    const { meta } = await import(schema);
    if (!meta) throw new Error(`${entry.name}/schema.ts has no \`meta\` export`);
    const tokensFile = join(COMPONENTS, entry.name, "tokens.ts");
    const tokens = existsSync(tokensFile) ? (await import(tokensFile)).tokens : undefined;
    specs.push({ meta, tokens, source: `src/components/${entry.name}` });
  }
  for (const file of readdirSync(SPECS).filter((f) => f.endsWith(".ts"))) {
    const { meta, tokens } = await import(join(SPECS, file));
    specs.push({ meta, tokens, source: `src/tokens/specs/${file}` });
  }
  const seen = new Map<string, string>();
  for (const s of specs) {
    const prev = seen.get(s.meta.name);
    if (prev) throw new Error(`component name "${s.meta.name}" used by ${prev} and ${s.source}`);
    seen.set(s.meta.name, s.source);
  }
  return specs.sort((a, b) => a.meta.name.localeCompare(b.meta.name));
};

const decls = (entries: [string, string][], indent = "  ") =>
  entries.map(([k, v]) => `${indent}--${k}: ${v};`);
const block = (selector: string, lines: string[], indent = "") =>
  [`${indent}${selector} {`, ...lines.map((l) => indent + l), `${indent}}`];

const header = (level: string, note: string) =>
  [`/* ${level} — generated by scripts/emit-tokens.ts from src/tokens. Do not edit. */`, `/* ${note} */`, ""];

const emitL1 = () =>
  [ ...header("L1 Primitives", "Literal foundations: bases, steps, ratios and single colours.")
  , ...block(":root", decls(Object.entries(primitives)))
  , ""
  ];

const emitL2 = () => {
  const lightLines = decls(Object.entries(light), "");
  const paletteBlocks = palettes.flatMap((p) =>
    block(`:root[data-palette="${p}"]`, decls(Object.entries(palette(p)))));
  return (
    [ ...header("L2 Semantic", "Defaults built from L1. Theme and palette attributes switch these values.")
    , ...block(":root", ["  color-scheme: dark;", ...decls(Object.entries(semantic))])
    , ""
    , ...paletteBlocks
    , ""
    , "@media (prefers-color-scheme: light) {"
    , ...block(':root:not([data-theme="dark"])', ["  color-scheme: light;", ...lightLines.map((l) => "  " + l)], "  ")
    , "}"
    , ...block(':root[data-theme="light"]', ["  color-scheme: light;", ...lightLines.map((l) => "  " + l)])
    , ""
    ]);
};

const emitLevel = (title: string, note: string, all: ComponentTokens[], pick: (c: ComponentTokens) => Token[]) => {
  const lines: string[] = [];
  for (const c of all) {
    const tokens = pick(c);
    if (!tokens.length) continue;
    lines.push("", `  /* --- ${c.name} --- */`);
    for (const t of tokens) lines.push(`  ${t.name}: ${t.value};${t.overridden ? " /* override */" : ""}`);
  }
  return [...header(title, note), ":root {", ...lines, "}", ""];
};

validateFoundations();
const specs = await loadSpecs();
const generated = specs.map(generateComponent);

if (process.argv.includes("--show")) {
  for (const s of specs) {
    const h = generateTokenHierarchy(s.meta);
    console.log(JSON.stringify(h, null, 2));
    console.log(JSON.stringify(toCSSVariables(h), null, 2));
  }
  process.exit(0);
}

const files: [string, string[]][] =
[ ["_l1-primitives.scss", emitL1()]
, ["_l2-semantic.scss", emitL2()]
, ["_l3-component.scss", emitLevel("L3 Component-Property", "--<component>-<property>: from L2. Also each component's role tones and state parameters.", generated, (c) => c.l3)]
, ["_l4-role.scss", emitLevel("L4 Role", "--<component>-<property>-<role>: from L3 by role recipe.", generated, (c) => c.l4)]
, ["_l5-state.scss", emitLevel("L5 State", "--<component>-<property>-<role>-<state>: from L4 by state recipe.", generated, (c) => c.l5)]
];
for (const [name, lines] of files) writeFileSync(join(OUT, name), lines.join("\n"));

const count = (f: (c: ComponentTokens) => Token[]) => generated.reduce((n, c) => n + f(c).length, 0);
console.log(
  `emitted ${specs.length} specs: L1 ${Object.keys(primitives).length}, L2 ${Object.keys(semantic).length}, ` +
  `L3 ${count((c) => c.l3)}, L4 ${count((c) => c.l4)}, L5 ${count((c) => c.l5)}`,
);
